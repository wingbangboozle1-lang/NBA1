#!/usr/bin/env python3
"""Build the static GitHub Pages site in docs/ from data/*.json.

Fails (exit 1) when:
  * a data row that must have a source has no https source link,
  * a source link points to a host outside the allow-list,
  * an internal link in the generated pages points to a missing file.
Run:  python3 scripts/build_site.py
"""
import html
import json
import os
import re
import sys
from urllib.parse import urlparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
DOCS = os.path.join(ROOT, "docs")
AS_OF = "2026-11-13"

ALLOWED_HOSTS = {
    "www.nba.com", "official.nba.com", "ak-static.cms.nba.com", "cdn.nba.com",
    "kansspelautoriteit.nl", "docs.github.com", "github.com",
}

NAV = [
    ("index.html", "Home"),
    ("summary.html", "Executive summary"),
    ("games.html", "Games (Nov 13–15)"),
    ("injuries.html", "Injuries"),
    ("picks.html", "Picks"),
    ("strategies.html", "Strategies & validation"),
    ("questions.html", "Questions"),
    ("suggestions.html", "Suggestions"),
    ("flagged.html", "Flagged for review"),
    ("sources.html", "Sources"),
]

errors = []


def load(name):
    with open(os.path.join(DATA, name + ".json"), encoding="utf-8") as f:
        return json.load(f)


def check_url(url, where):
    if not url:
        return
    p = urlparse(url)
    if p.scheme != "https" or p.netloc not in ALLOWED_HOSTS:
        errors.append(f"{where}: source host not allowed: {url}")


def require_source(url, where):
    if not url:
        errors.append(f"{where}: missing source link")
        return
    check_url(url, where)


def esc(v):
    return html.escape("" if v is None else str(v))


def link(url, label=None):
    if not url:
        return '<span class="flag">unverified — no source</span>'
    return f'<a href="{esc(url)}" target="_blank" rel="noopener">{esc(label or "source")}</a>'


def table(headers, rows, table_id=None, filterable=True):
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = []
    for r in rows:
        body.append("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    tid = f' id="{table_id}"' if table_id else ""
    search = ('<input class="filter" type="search" placeholder="Filter rows…" '
              f'data-target="{table_id}" aria-label="Filter rows">') if (table_id and filterable) else ""
    return (f'{search}<div class="tablewrap"><table{tid}><thead><tr>{head}</tr></thead>'
            f'<tbody>{"".join(body)}</tbody></table></div>')


def page(filename, title, body, lead=""):
    parts = []
    for href, label in NAV:
        cls = ' class="active"' if href == filename else ""
        parts.append(f'<a href="{href}"{cls}>{esc(label)}</a>')
    nav = "".join(parts)
    html_doc = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} · NBA1</title>
<link rel="stylesheet" href="assets/style.css">
</head>
<body>
<header class="top">
  <div class="brand"><a href="index.html">NBA1</a><span>Research dashboard · data as of {AS_OF}</span></div>
  <nav>{nav}</nav>
</header>
<main>
<h1>{esc(title)}</h1>
{f'<p class="lead">{lead}</p>' if lead else ''}
{body}
</main>
<footer>
  <p>Every table row links to an official source. Values that cannot be confirmed are left blank and flagged.
  Nothing here is betting advice. Gambling in NL is regulated: see <a href="questions.html">Questions</a> Q-03 and Q-04.</p>
  <p>Generated by <code>scripts/build_site.py</code> from <code>data/*.json</code>.</p>
</footer>
<script src="assets/app.js"></script>
</body>
</html>
"""
    with open(os.path.join(DOCS, filename), "w", encoding="utf-8") as f:
        f.write(html_doc)


def cards(items):
    return '<div class="cards">' + "".join(
        f'<a class="card" href="{href}"><h3>{esc(t)}</h3><p>{esc(d)}</p></a>' for href, t, d in items
    ) + "</div>"


def build():
    os.makedirs(DOCS, exist_ok=True)
    os.makedirs(os.path.join(DOCS, "assets"), exist_ok=True)
    with open(os.path.join(DOCS, ".nojekyll"), "w") as f:
        f.write("")

    games = load("games")
    injuries = load("injuries")
    flags = load("flags")
    questions = load("questions")
    suggestions = load("suggestions")
    strategies = load("strategies")
    summary = load("summary")
    sources = load("sources")

    source_ids = {s["id"] for s in sources}

    # ---------- validation ----------
    for s in sources:
        require_source(s["url"], f"sources {s['id']}")
    for g in games["games"]:
        require_source(g["source_url"], f"games {g['date']} {g['away']}@{g['home']}")
        check_url(g["preview_url"], "games preview")
    for r in injuries["rows"]:
        require_source(r["source_url"], f"injuries {r['player']}")
        check_url(r["matchup_source_url"], "injuries matchup")
    for f_ in flags:
        require_source(f_["source_url"], f"flag {f_['id']}")
    for q in questions:
        if q["status"] == "answered" or q["source_url"]:
            require_source(q["source_url"], f"question {q['id']}")
        else:
            # decision items with no external source are allowed only when status is unanswered
            if q["status"] != "unanswered":
                errors.append(f"question {q['id']}: no source but not unanswered")
        check_url(q["source_url"], f"question {q['id']}")

    # ---------- pages ----------
    n_games = len(games["games"])
    n_inj = len(injuries["rows"])
    n_reason_blank = sum(1 for r in injuries["rows"] if r["reason_printed"] is None)
    n_flags = len(flags)

    home_cards = cards([
        ("summary.html", "Executive summary", "What is verified, what is missing, and what is blocked."),
        ("games.html", "Games, Nov 13–15", f"{n_games} scheduled games, official NBA times and records."),
        ("injuries.html", "Injuries", f"{n_inj} rows from the official 11/13 12:00 PM report."),
        ("picks.html", "Picks", "No picks generated. Reason and blockers shown."),
        ("strategies.html", "Strategies & validation", "Validation gates defined. No strategy evaluated."),
        ("questions.html", "Questions", "Answered, partly answered, and open questions."),
        ("suggestions.html", "Suggestions", "Site and process improvements. Choose before anything changes."),
        ("flagged.html", "Flagged for review", f"{n_flags} irregularities and unverified items."),
        ("sources.html", "Sources", "Every official source used, with links."),
    ])
    status_html = f"""
<div class="status">
  <strong>Status:</strong> data collection done for schedule and injuries. Models, correlation values,
  leaderboard, and picks are <strong>not produced</strong> — the verified inputs are missing (see Questions).
</div>
<p class="lead">Official-source research dashboard for NBA games on Nov 13–15, 2026. Every row links to its source.</p>
"""
    page("index.html", "Dashboard", status_html + home_cards)

    # summary
    bullets = "".join(f"<li>{esc(b)}</li>" for b in summary["bullets"])
    body = f'<div class="status"><strong>Headline:</strong> {esc(summary["headline"])}</div><ul class="bullets">{bullets}</ul>'
    body += '<h2>Key numbers</h2>' + table(
        ["Metric", "Value", "Basis / source"],
        [
            ["Games in 3-day window", str(n_games), link(games["games"][0]["source_url"], "NBA.com games pages (Nov 13, 14, 15)")],
            ["Injury rows (11/13 12:00 PM)", str(n_inj), link(injuries["rows"][0]["source_url"], "NBA injury report PDF")],
            ["Injury rows with no printed reason", str(n_reason_blank), link(injuries["rows"][0]["source_url"], "NBA injury report PDF")],
            ["Injury rows excluded (no team)", "14", link(injuries["rows"][0]["source_url"], "NBA injury report PDF (see Flagged F-03)")],
            ["Strategies evaluated", "0", "Blocked: no verified odds or game logs (Q-06, Q-07)"],
            ["Picks generated", "0", "Blocked (Q-04, Q-06, Q-07)"],
        ],
        "keynums",
        filterable=False,
    )
    page("summary.html", "Executive summary", body, "What matters most, in plain terms.")

    # games
    rows = []
    for g in games["games"]:
        rows.append([
            esc(g["date"]), esc(g["time_et"]), esc(g["away"]), esc(g["home"]),
            esc(g["away_record"] or "—"), esc(g["home_record"] or "—"),
            esc(g["game_id"]),
            link(g["source_url"], "games page"),
            link(g["preview_url"], "preview"),
        ])
    body = table(["Date", "Time (ET)", "Away", "Home", "Away record", "Home record", "Game ID", "Source", "Preview"], rows, "games")
    body += f'<p class="note">{esc(games["timezone_note"])} Records are as displayed at retrieval (see Flagged F-08). Team order follows the NBA.com games page, treated as away-then-home (matches injury-report codes where printed; not separately confirmed — see Flagged F-14).</p>'
    page("games.html", "Games, Nov 13–15, 2026", body, f"{n_games} games in the 3-day window, per the official NBA games pages.")

    # injuries
    rows = []
    for r in injuries["rows"]:
        reason = esc(r["reason_printed"]) if r["reason_printed"] else '<span class="flag">not printed — flagged</span>'
        mb = esc(r["matchup"]) + (' <span class="tag">implied</span>' if r["matchup_basis"].startswith("implied") else "")
        rows.append([
            esc(r["team"]), esc(r["player"]), esc(r["status"]), reason, mb,
            link(r["source_url"], "PDF"),
        ])
    body = table(["Team", "Player", "Status", "Reason (as printed)", "Matchup", "Source"], rows, "injuries")
    body += f"""
<h2>What this table does not show</h2>
<ul class="bullets">
  <li>Rotation minutes and production impact: <strong>not computed</strong> (no verified minutes data; see Questions Q-08).</li>
  <li>Game flow analysis: <strong>not produced</strong>.</li>
  <li>Rows excluded: 14 rows with no printed team and 9 "NOT YET SUBMITTED" 11/14 rows (see Flagged F-03, F-05).</li>
  <li>Text was extracted from a PDF. Spot-check each row against the source before use (F-04).</li>
</ul>
<p class="note">Rule text: <a href="https://official.nba.com/nba-injury-report-2026-27-season/" target="_blank" rel="noopener">NBA official injury report rules</a>.</p>"""
    page("injuries.html", "Injury report — 11/13/26 12:00 PM", body,
         f"{n_inj} rows copied from the official game-day report. {n_reason_blank} rows have no printed reason and are flagged.")

    # picks
    body = f"""
<div class="status"><strong>No picks have been generated.</strong> The system cannot produce picks without verified lines and verified game logs. Neither exists in this project yet.</div>
<h2>Slates in the 3-day window</h2>
{table(["Date", "Games", "Source"], [
    ["2026-11-13", "9", link(games["games"][0]["source_url"], "NBA.com games page")],
    ["2026-11-14", "5", link(games["games"][9]["source_url"], "NBA.com games page")],
    ["2026-11-15", "9", link(games["games"][14]["source_url"], "NBA.com games page")],
], "slates", filterable=False)}
<h2>What is needed before picks can be produced</h2>
<ul class="bullets">
  <li>A verified odds source with clear licence terms (Q-07).</li>
  <li>Verified historical game logs for correlation values (Q-06).</li>
  <li>A passed validation gate for each strategy (see Strategies & validation).</li>
  <li>A legal review of any output that could be read as offering wagers in NL (Q-04; Ksa licence rules, Q-03).</li>
</ul>"""
    page("picks.html", "Picks", body, "The picks engine is not run. Here is what it needs and what the slate is.")

    # strategies
    fam_rows = [[esc(f_["family"]), esc(f_["status"]), esc(f_["blocked_by"])] for f_ in strategies["families"]]
    gate_rows = [[esc(g["id"]), esc(g["name"]), esc(g["proposal"]), esc(g["status"])] for g in strategies["gates"]]
    body = f"""
<div class="status"><strong>Status:</strong> {esc(strategies["status"])}</div>
<h2>Strategy families</h2>{table(["Family", "Status", "Blocked by"], fam_rows, "families")}
<h2>Validation gates (proposed)</h2>{table(["ID", "Gate", "Proposal", "Status"], gate_rows, "gates")}
<p class="note">{esc(strategies["note"])}</p>
<h2>Leaderboard</h2><p>Empty. No strategy has passed or been tested.</p>
<h2>Correlation values</h2><p>Empty. Not computed. Requires game logs (Q-06). Values are left blank rather than estimated.</p>"""
    page("strategies.html", "Strategies & validation", body, "Framework only. No results are shown because none have been produced.")

    # questions
    rows = []
    for q in questions:
        rows.append([esc(q["id"]), esc(q["question"]), esc(q["status"]), esc(q["answer"]), esc(q["needed_for"]),
                     link(q["source_url"], "source") if q["source_url"] else '<span class="flag">decision item — no source</span>'])
    body = table(["ID", "Question", "Status", "Answer / current state", "Needed for", "Source"], rows, "questions")
    page("questions.html", "Questions — answered, partial, and open", body,
         "What is known, what is not, and what needs a decision before anything can be reasonably decided.")

    # suggestions
    rows = []
    for s in suggestions:
        rows.append([esc(s["id"]), esc(s["title"]), esc(s["detail"]), esc(s["benefit"]), esc(s["effort"]), esc(s["risk"]),
                     '<span class="tag">Pending your choice</span>'])
    body = table(["ID", "Suggestion", "Detail", "Benefit", "Effort", "Risk", "Decision"], rows, "suggestions")
    body += '<p class="note">None of these are implemented. Pick the ones to pursue and say so; each one then becomes a task.</p>'
    page("suggestions.html", "Suggestions — choose before anything changes", body,
         "Improvements to the site and process. Review and choose; nothing is implemented until you decide.")

    # flagged
    rows = []
    for f_ in flags:
        rows.append([esc(f_["id"]), esc(f_["category"]), esc(f_["item"]), esc(f_["detail"]), esc(f_["severity"]),
                     link(f_["source_url"], "source"), esc(f_["status"])])
    body = table(["ID", "Category", "Item", "Detail", "Severity", "Source", "Status"], rows, "flags")
    body += '<p class="note">Flagged items do not block the site. Request changes on any item you disagree with.</p>'
    page("flagged.html", "Flagged for review", body,
         "Irregularities and unverified items, with source links, for your review after the site is live.")

    # sources
    rows = [[esc(s["id"]), esc(s["title"]), esc(s["used_for"]), link(s["url"], s["url"].replace("https://", "")[:60])] for s in sources]
    body = table(["ID", "Source", "Used for", "URL"], rows, "sources")
    body += '<p class="note">Sources were retrieved on 2026-11-13. A fetch that failed or returned no usable content is recorded in <a href="flagged.html">Flagged for review</a>, not filled in.</p>'
    page("sources.html", "Sources", body, "Every source with its link. Only these sources are used for any value on this site.")

    # ---------- internal link check ----------
    existing = {f for f in os.listdir(DOCS) if f.endswith(".html")}
    for f in existing:
        with open(os.path.join(DOCS, f), encoding="utf-8") as fh:
            text = fh.read()
        for href in re.findall(r'href="([^"]+)"', text):
            if href.startswith(("http://", "https://", "#", "mailto:")):
                continue
            target = href.split("#")[0]
            if target and target not in existing and not target.startswith("assets/"):
                errors.append(f"{f}: broken internal link -> {href}")
            if target.startswith("assets/") and not os.path.exists(os.path.join(DOCS, target)):
                errors.append(f"{f}: missing asset -> {href}")

    if errors:
        print("BUILD FAILED:")
        for e in errors:
            print(" -", e)
        return 1
    print(f"built {len(existing)} pages into docs/ · games={n_games} injuries={n_inj} flags={n_flags}")
    return 0


if __name__ == "__main__":
    sys.exit(build())
