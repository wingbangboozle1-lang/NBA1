#!/usr/bin/env python3
"""Resolve recurring probe/coordination merge conflicts (session arena/697fca1e-nba1).
Probe pair: keep the NEWEST internally-consistent probe run of the two sides.
verification.html: regenerated by the current generator afterwards (CI no-op invariant).
COORDINATION.md: keep BOTH sides (other sessions' sections verbatim, my section last).
"""
import json, re, subprocess, sys

def show(ref, path):
    return subprocess.run(["git", "show", f"{ref}:{path}"], capture_output=True,
                          text=True).stdout

ours_sha, theirs_sha = sys.argv[1], sys.argv[2]

# --- probe_official.json ---
ours = json.loads(show(ours_sha, "data/raw/probe_official.json"))
theirs = json.loads(show(theirs_sha, "data/raw/probe_official.json"))
o_ok = ours["probe"]["urls_probed"] == len(ours["results"])
t_ok = theirs["probe"]["urls_probed"] == len(theirs["results"])
pick = None
if o_ok and (not t_ok or ours["probe"]["probed_at_utc"] >= theirs["probe"]["probed_at_utc"]):
    pick = ours_sha
elif t_ok:
    pick = theirs_sha
if pick is None:
    sys.exit("no consistent probe record on either side")
src = show(pick, "data/raw/probe_official.json")
open("data/raw/probe_official.json", "w", encoding="utf-8").write(src)
print("probe json <-", pick, ours["probe"]["probed_at_utc"] if pick == ours_sha else theirs["probe"]["probed_at_utc"])

# --- verification.html: take the same side, then regenerate over it ---
vh = show(pick, "verification.html")
open("verification.html", "w", encoding="utf-8").write(vh)

# --- COORDINATION.md: keep both sides; my section (from ours) goes last ---
s = open("COORDINATION.md", encoding="utf-8").read()
m = re.search(r"<<<<<<< HEAD\n(.*?)=======\n(.*?)>>>>>>> [^\n]*\n", s, re.S)
if m:
    head_side, their_side = m.group(1), m.group(2)
    i = head_side.find("## 18. Session `arena/697fca1e-nba1`")
    if i == -1:
        merged = their_side.rstrip() + "\n"
    else:
        merged = their_side.rstrip() + "\n\n---\n\n" + head_side[i:]
    s = s[:m.start()] + merged + s[m.end():]
    open("COORDINATION.md", "w", encoding="utf-8").write(s)
    print("coord resolved: both kept, session section last")
else:
    print("coord: no conflict markers found")
